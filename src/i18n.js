export function translate(lang, key, vars) {
  let s = (S[lang] && S[lang][key]) || S.en[key] || key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}

export const isRtl = (lang) => !!LANGS.find((l) => l.code === lang && l.rtl);
